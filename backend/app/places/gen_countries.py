"""Regenerate seed/countries.json: every country's name in the languages people write trips in.

Dev tool, not used by the app at run time:  pip install babel && python -m app.places.gen_countries
Names come from the Unicode CLDR (via Babel). Names that are also everyday words ("Mali" is
Italian for "evils", "Chad" is a first name) are left out, so a trip text does not "mention" them.
"""
import json
import re
import unicodedata
from pathlib import Path

from babel import Locale

OUT = Path(__file__).resolve().parents[2] / "seed" / "countries.json"
LANGS = ["en", "it", "es", "fr", "de", "pt"]
# words that are a country's name but mostly mean something else in a trip description
SKIP = {"mali", "chad", "niger", "togo", "georgia", "jordan", "jersey", "guinea", "man",
        "turkey", "china", "chile", "dominica", "congo", "sudan", "samoa", "panama", "guernsey",
        "monaco", "malta", "nauru", "tonga", "cuba", "peru", "iran", "oman", "india"}
# kept although listed above: they are rarely anything but the country in a travel text
KEEP = {"chile", "china", "turkey", "cuba", "peru", "iran", "oman", "india", "malta", "monaco",
        "panama", "samoa", "tonga"}
EXTRA = {
    "US": ["usa", "u s a", "stati uniti d america"],
    "GB": ["uk", "inghilterra", "england", "scozia", "scotland", "galles", "wales", "gran bretagna",
           "great britain", "irlanda del nord", "northern ireland", "regno unito"],
    "NL": ["olanda", "holland", "paesi bassi"],
    "CZ": ["repubblica ceca", "czech republic"],
    "MM": ["birmania", "burma"],
    "CI": ["costa d avorio", "ivory coast"],
    "KR": ["corea del sud", "south korea", "corea"],
    "KP": ["corea del nord", "north korea"],
    "CD": ["repubblica democratica del congo"],
    "VA": ["vaticano"],
    "BO": ["bolivia"],
}


def norm(s: str) -> str:
    s = "".join(c for c in unicodedata.normalize("NFKD", s.lower()) if not unicodedata.combining(c))
    return re.sub(r"[^a-z0-9]+", " ", s).strip()


def main():
    names: dict[str, set[str]] = {}
    en = Locale("en").territories
    for cc in en:
        if not re.fullmatch(r"[A-Z]{2}", cc) or cc in ("ZZ", "EU", "EZ", "UN", "QO", "XA", "XB"):
            continue
        for lang in LANGS:
            n = Locale(lang).territories.get(cc)
            if n:
                names.setdefault(cc, set()).add(norm(n))
    for cc, extra in EXTRA.items():
        names.setdefault(cc, set()).update(norm(x) for x in extra)
    owners: dict[str, set[str]] = {}
    for cc, ns in names.items():
        for n in ns:
            owners.setdefault(n, set()).add(cc)
    out = {}
    for cc in sorted(names):
        keep = sorted(n for n in names[cc]
                      if len(owners[n]) == 1 and len(n) >= 4 and (n not in SKIP or n in KEEP))
        out[cc] = {"name": en[cc], "names": keep}
    doc = {"_doc": "ISO 3166-1 alpha-2 -> English name + the names a trip text may use "
                   "(lowercase ascii, en/it/es/fr/de/pt from CLDR). Generated by app.places.gen_countries.",
           "countries": out}
    OUT.write_text(json.dumps(doc, ensure_ascii=False, indent=0) + "\n", encoding="utf-8")
    print(f"{len(out)} countries -> {OUT}")


if __name__ == "__main__":
    main()
