"""Every trek in the world (Manu, 2026-11-14): the waymarked routes of OpenStreetMap outside the 8
trekking countries, generated by tools/trails/world_tail.py, one file per country:

  world/<cc>.json   {"trails": [...], "geo": {id: {numbers, points, segments, enc}}}
  world/_dots.json  one row per trek for the globe: [id, name, lat, lon, difficulty 0-3, days, rank]

Hundreds of thousands of treks: never all in memory as models. The globe reads the dots (the
famous ones at once, the rest by 10-degree cell as you zoom in); a country's file is read only
when one of its treks is opened, and only a few countries stay in memory.
"""
from __future__ import annotations

import json
import math
from functools import lru_cache
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORLD = HERE / "world"
CELL = 10  # degrees: the globe asks for the small treks of one cell at a time
FAR_RANK = 4  # treks of this rank and up come with the first answer (seen from far away)


@lru_cache(maxsize=12)
def _country(cc: str) -> tuple[dict[str, dict], dict[str, dict]]:
    f = WORLD / f"{cc.lower()}.json"
    if not f.exists():
        return {}, {}
    doc = json.loads(f.read_text(encoding="utf-8"))
    return {t["id"]: t for t in doc["trails"]}, doc["geo"]


def row(trail_id: str) -> dict | None:
    return _country(trail_id[:2])[0].get(trail_id)


def decode(s: str, dims: int = 3, prec=(1e5, 1e5, 1)) -> list[list[float]]:
    out, last, i = [], [0] * dims, 0
    while i < len(s):
        p = []
        for k in range(dims):
            shift = res = 0
            while True:
                b = ord(s[i]) - 63
                i += 1
                res |= (b & 0x1F) << shift
                shift += 5
                if b < 0x20:
                    break
            last[k] += ~(res >> 1) if res & 1 else res >> 1
            p.append(round(last[k] / prec[k], 5) if prec[k] != 1 else last[k])
        out.append(p)
    return out


def _km(a, b) -> float:
    p1, p2 = math.radians(a[0]), math.radians(b[0])
    h = math.sin((p2 - p1) / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(math.radians(b[1] - a[1]) / 2) ** 2
    return 6371 * 2 * math.asin(math.sqrt(min(1.0, h)))


def geo(trail_id: str) -> dict | None:
    g = _country(trail_id[:2])[1].get(trail_id)
    if not g:
        return None
    line = decode(g["enc"])
    d, prof = 0.0, []
    for i, p in enumerate(line):
        if i:
            d += _km(line[i - 1], p)
        prof.append([round(d, 2), p[2]])
    step = max(1, len(prof) // 160)
    prof = prof[::step] + ([prof[-1]] if (len(prof) - 1) % step else [])
    return {**{k: v for k, v in g.items() if k != "enc"}, "id": trail_id, "how": "osm", "line": line, "profile": prof}


@lru_cache
def dots() -> list[list]:
    """[id, name, lat, lon, difficulty, days, rank]; the iconic treks of the world rank 6."""
    f = WORLD / "_dots.json"
    rows = json.loads(f.read_text(encoding="utf-8"))["dots"] if f.exists() else []
    top = iconic()
    for r in rows:
        if r[0] in top:
            r[6] = 6
    return rows


@lru_cache
def _cells() -> dict[tuple[int, int], list[list]]:
    out: dict[tuple[int, int], list[list]] = {}
    for r in dots():
        if r[6] < FAR_RANK:
            out.setdefault((int(r[2] // CELL), int(r[3] // CELL)), []).append(r)
    return out


def far() -> list[list]:
    return [r for r in dots() if r[6] >= FAR_RANK]


def cell(i: int, j: int) -> list[list]:
    return _cells().get((i, j), [])


def countries() -> list[str]:
    return sorted(f.stem.upper() for f in WORLD.glob("[a-z][a-z].json")) if WORLD.exists() else []


@lru_cache
def iconic() -> frozenset[str]:
    """The treks known the world over (Manu 2026-11-14: they get a drawing later): seen from space."""
    f = WORLD / "_iconic.json"
    return frozenset(r["id"] for r in json.loads(f.read_text(encoding="utf-8"))["treks"] if r.get("id")) if f.exists() else frozenset()
